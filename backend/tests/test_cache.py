# Test 4 — Cache Key Consistency
# ---------------------------------------------------------------------------

def test_cache_key_deterministic_same_query():
    """
    Test 4: The same query always produces the exact same cache key.
    No random values, no timestamps — purely deterministic SHA-256.
    """
    query = "Find the latest AI news"
    key1 = generate_cache_key(query)
    key2 = generate_cache_key(query)
    key3 = generate_cache_key(query)

    assert key1 == key2 == key3, \
        "Same query must always produce the same cache key"
    assert key1.startswith(CACHE_KEY_PREFIX), \
        f"Cache key must start with '{CACHE_KEY_PREFIX}'"


def test_cache_key_normalization_consistency():
    """
    Test 4b: Queries that differ only in case/whitespace/punctuation
    produce the SAME cache key after normalization.
    """
    q1 = "Find the latest AI news"
    q2 = "find the latest ai news"
    q3 = "  Find  The  Latest  AI  News  "

    key1 = generate_cache_key(q1)
    key2 = generate_cache_key(q2)
    key3 = generate_cache_key(q3)

    assert key1 == key2 == key3, \
        "Case/whitespace variations must produce the same cache key"


def test_cache_key_different_queries_produce_different_keys():
    """
    Test 4c: Different queries must produce different cache keys.
    """
    key_ai = generate_cache_key("Find the latest AI news")
    key_cricket = generate_cache_key("India wins cricket match")

    assert key_ai != key_cricket, \
        "Different queries must produce different cache keys"


def test_cache_key_contains_sha256_digest():
    """
    Test 4d: The cache key ends with a valid SHA-256 hex digest.
    """
    query = "Show the current news analytics"
    normalized = normalize_query(query)
    expected_digest = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    expected_key = f"{CACHE_KEY_PREFIX}{expected_digest}"

    actual_key = generate_cache_key(query)
    assert actual_key == expected_key, \
        f"Expected key '{expected_key}', got '{actual_key}'"


