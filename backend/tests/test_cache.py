def test_cache_hit_rate_dynamic_calculation():
    """
    Test 6: Cache Hit Rate = hits / (hits + misses), calculated dynamically.
    Verifies: 2 hits + 1 miss = 66.67% hit rate.
    """
    reset_cache_counters()
    reset_redis_client()

    query = "Compare BBC and NDTV coverage"
    key = generate_cache_key(query)

    # 2 hits
    fake_redis, _ = _make_fake_redis(stored={key: "Cached response"})
    with patch("app.utils.redis_cache._get_redis_client", return_value=fake_redis):
        cache_get(query)   # HIT
        cache_get(query)   # HIT

    # 1 miss
    fake_redis2, _ = _make_fake_redis(stored={})
    with patch("app.utils.redis_cache._get_redis_client", return_value=fake_redis2):
        cache_get("completely different query that is not cached")  # MISS

    rate = get_cache_hit_rate()
    assert 0.60 <= rate <= 0.70, \
        f"Expected ~0.667 hit rate (2 hits, 1 miss), got {rate}"


def test_cache_hit_rate_zero_when_no_requests():
    """
    Test 6b: Hit rate is 0.0 when no cache operations have occurred.
    """
    reset_cache_counters()
    rate = get_cache_hit_rate()
    assert rate == 0.0, f"Expected 0.0 hit rate with no requests, got {rate}"


def test_cache_hit_rate_changes_with_more_hits():
    """
    Test 6c: Hit rate increases dynamically as more hits occur.
    """
    reset_cache_counters()
    reset_redis_client()

    query = "Find AI news"
    key = generate_cache_key(query)

    # First: 1 miss
    fake_miss = _make_fake_redis(stored={})[0]
    with patch("app.utils.redis_cache._get_redis_client", return_value=fake_miss):
        cache_get("not cached")

    rate_after_miss = get_cache_hit_rate()
    assert rate_after_miss == 0.0

    # Then: 1 hit
    fake_hit = _make_fake_redis(stored={key: "Response"})[0]
    with patch("app.utils.redis_cache._get_redis_client", return_value=fake_hit):
        cache_get(query)

    rate_after_hit = get_cache_hit_rate()
    assert rate_after_hit > rate_after_miss, \
        "Hit rate must increase after a cache hit"
    assert rate_after_hit == 0.5, \
        f"Expected 0.5 (1 hit, 1 miss), got {rate_after_hit}"
