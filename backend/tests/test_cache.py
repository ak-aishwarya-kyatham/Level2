def _make_fake_redis(stored: dict = None):
    """Create a mock Redis client backed by an in-memory dict."""
    store = stored or {}
    mock = MagicMock()

    def _get(key):
        return store.get(key)

    def _setex(key, ttl, value):
        store[key] = value
        return True

    def _delete(key):
        store.pop(key, None)
        return 1

    mock.ping.return_value = True
    mock.get.side_effect = _get
    mock.setex.side_effect = _setex
    mock.delete.side_effect = _delete
    return mock, store


